/**
 * Dynamic lookup helper that returns known definitions or creates a clean fallback.
 */
export function lookupDictionaryWord(rawWord: string, contextSentence?: string): WordDefinition {
  const clean = rawWord.toLowerCase().replace(/[^a-zA-Z]/g, '');

  if (LOCAL_DICTIONARY[clean]) {
    return LOCAL_DICTIONARY[clean];
  }

  // Fallback intelligent entry
  const capitalized = clean.charAt(0).toUpperCase() + clean.slice(1);
  return {
    word: clean,
    phonetic: `/${clean}/`,
    partOfSpeech: 'vocabulary word',
    definitions: [
      `General meaning of '${clean}' in native spoken English.`,
      `Used in spoken expression to convey specific contextual nuance.`,
    ],
    contextMeaning: contextSentence
      ? `在句子 "${contextSentence.slice(0, 45)}..." 中表达具体语境含义。`
      : `用于日常口语表达。`,
    sampleSentenceEn: contextSentence || `Pay attention to the native pronunciation of ${clean}.`,
    sampleSentenceZh: '请注意该单词在原声视频中的发音与连读技巧。',
  };
}
